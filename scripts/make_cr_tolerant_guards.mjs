// Generates CR-tolerant copies of the 29b and 29e migrations WITHOUT editing the originals.
// Why: the originals compare md5(prosrc) with the Staging baseline, whose stored text had CRLF line endings. Production stores the same code with LF
// (verified read-only 2026-10-21: the LF body equals rollback/29_dispatch_rollback.sql; its CRLF form reproduces the expected md5). The guard would refuse a correct database.
// The generated guard accepts a function when EITHER the raw md5 equals the original baseline OR the CR-stripped md5 equals the LF baseline. Everything else is byte-identical.
// Usage: node scripts/make_cr_tolerant_guards.mjs           (writes supabase/production/*.crtolerant.sql)
//        node scripts/make_cr_tolerant_guards.mjs --check   (verifies the generated files are current and differ from the originals only in guard lines)
import fs from "node:fs";
import path from "node:path";
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
// LF baselines where they differ from the original (measured on Production, equal to the pre-29 bodies in the 29 rollback file). Absent = same as the original.
const LF = {
  update_order_status: "c48f233d5a6addaf51cdf9861080f9b7",
  guard_orders_write: "45c650e234c1bd71c7c3ccba88cac87e",
  transfer_customer_owner: "b2bfa0750971a715945b17109e52a38c",
};
const files = ["29b_dispatch_and_live_orders", "29e_enforce_dispatch"];
const check = process.argv.includes("--check");
let bad = 0;
for (const f of files) {
  const src = fs.readFileSync(path.join(root, "supabase", `${f}.sql`), "utf8");
  if (src.includes("\r")) throw new Error(`${f}.sql contains CR characters; refusing`);
  const lines = src.split("\n");
  const out = [];
  let changed = 0;
  for (let i = 0; i < lines.length; i++) {
    let l = lines[i];
    if (l.includes("select md5(p.prosrc) into v_md5 from pg_proc p")) {
      l = l.replace("select md5(p.prosrc) into v_md5", "select md5(p.prosrc), md5(replace(p.prosrc, chr(13), '')) into v_md5, v_crs");
      changed++;
    } else {
      const m = l.match(/if v_md5 is distinct from '([0-9a-f]{32})' then raise exception '(\w+) is not the expected definition/);
      if (m) {
        const lf = LF[m[2]] ?? m[1];
        l = l.replace(`if v_md5 is distinct from '${m[1]}' then`, `if v_md5 is distinct from '${m[1]}' and v_crs is distinct from '${lf}' then`);
        changed++;
      }
    }
    if (/^declare v_md5 text;$/.test(l)) { l = "declare v_md5 text; v_crs text;"; changed++; }
    out.push(l);
  }
  const header = `-- GENERATED by scripts/make_cr_tolerant_guards.mjs from ${f}.sql. Do not edit. Only the md5 guard lines differ from the original.\n`;
  const text = header + out.join("\n");
  const dest = path.join(root, "supabase", "production", `${f}.crtolerant.sql`);
  if (check) {
    const cur = fs.existsSync(dest) ? fs.readFileSync(dest, "utf8") : "";
    const o = out, s = lines; // line-for-line: same number of lines, and only guard lines differ
    const diff = o.filter((x, i) => x !== s[i]).length;
    const guardOnly = o.every((x, i) => x === s[i] || /v_crs|select md5\(p\.prosrc\)/.test(x));
    console.log(`${f}: ${cur === text ? "current" : "STALE"}; changed lines=${diff}; guard-only=${guardOnly}`);
    if (cur !== text || !guardOnly) bad++;
  } else {
    fs.writeFileSync(dest, text);
    console.log(`${f}: wrote ${path.relative(root, dest)} (${changed} guard lines changed)`);
  }
}
process.exit(bad ? 1 : 0);
